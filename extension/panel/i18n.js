const PANEL_LANGUAGES = ["en", "fr", "ar"];
let panelLang = "en";

/** The panel's words for `key` in its language (English if missing). */
function t(key, ...values) {
  const v = PANEL_TEXT[panelLang]?.[key] ?? PANEL_TEXT.en[key];
  return typeof v === "function" ? v(...values) : v ?? key;
}

/** The language a new panel starts in: the browser's, if it's one of ours. */
function browserLanguage() {
  const l = (navigator.language || "en").slice(0, 2).toLowerCase();
  return PANEL_LANGUAGES.includes(l) ? l : "en";
}

/** Shows the panel in `lang`: every data-i18n element, the direction, the switch. */
function applyLanguage(lang) {
  panelLang = PANEL_LANGUAGES.includes(lang) ? lang : "en";
  document.documentElement.lang = panelLang;
  document.documentElement.dir = panelLang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n, ...(el.dataset.i18nArg ? [Number(el.dataset.i18nArg)] : [])); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  const select = document.getElementById("langSelect");
  if (select) select.value = panelLang;
}
